package br.uel.biblioteca.controller;

public class EmprestimoForm {

    private String matricula;
    private String codigosPatrimonio;

    public String getMatricula() {
        return matricula;
    }

    public void setMatricula(String matricula) {
        this.matricula = matricula;
    }

    public String getCodigosPatrimonio() {
        return codigosPatrimonio;
    }

    public void setCodigosPatrimonio(String codigosPatrimonio) {
        this.codigosPatrimonio = codigosPatrimonio;
    }
}
